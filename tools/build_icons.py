"""
Generate tools/css/icons.generated.css from the lucide-static SVG set.

Every icon becomes a CSS-mask rule so that icons can be rendered from Dash as a
plain <span class="lucide lucide-<name>"> that inherits `currentColor` – this is
visually identical to the inline <svg> icons used by lucide-react in the
original Next.js app (same 24x24 geometry, 2px stroke, round caps).

Usage (only needed when you add a new icon; the generated CSS is committed):
    npm --prefix tools/css install            # installs lucide-static
    python tools/build_icons.py
    npm --prefix tools/css run build          # re-compiles assets/style.css
"""
from __future__ import annotations

import base64  # noqa: F401  (kept for easy switch to base64 data URIs)
import re
import sys
import urllib.parse
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
LUCIDE = Path(sys.argv[1]) if len(sys.argv) > 1 else ROOT / "tools" / "css" / "node_modules" / "lucide-static" / "icons"
OUT = ROOT / "tools" / "css" / "icons.generated.css"

# lucide-react (PascalCase) → lucide-static file name, for icons that were renamed upstream
ALIASES = {"alert-triangle": "triangle-alert", "check-circle-2": "circle-check", "x-circle": "circle-x",
           "loader2": "loader-circle", "map": "map", "circle-check-icon": "circle-check"}

# scan the project for icon("name") usages + the extras listed here
EXTRA = [
    "activity", "triangle-alert", "archive", "arrow-left", "arrow-right", "arrow-up-down", "book-open", "bot", "calendar",
    "check", "circle-check", "chevron-down", "chevron-left", "chevron-right", "chevron-up", "chevrons-up-down", "circle",
    "construction", "download", "external-link", "file-code", "file-down", "file-spreadsheet", "file-text", "file-type",
    "file-x", "globe", "history", "info", "languages", "layout-dashboard", "loader-circle", "log-in", "log-out", "map",
    "map-pin", "messages-square", "octagon-x", "paperclip", "pencil", "plug", "plus", "printer", "refresh-cw",
    "rotate-ccw", "save", "scan-text", "scroll-text", "search", "send", "shield-check", "skip-forward", "sparkles",
    "trash-2", "upload", "user", "x", "circle-x", "copy", "link", "minus", "eye",
]


def used_names() -> set[str]:
    names = set(EXTRA)
    for py in list(ROOT.glob("pages/*.py")) + list(ROOT.glob("utils/*.py")) + [ROOT / "app.py"]:
        if py.exists():
            names.update(re.findall(r"""icon\(\s*["']([a-z0-9-]+)["']""", py.read_text(encoding="utf-8")))
            names.update(re.findall(r"""["']icon["']\s*:\s*["']([a-z0-9-]+)["']""", py.read_text(encoding="utf-8")))
    return {ALIASES.get(n, n) for n in names}


def to_data_uri(svg: str) -> str:
    svg = re.sub(r"<!--.*?-->", "", svg, flags=re.S)
    svg = re.sub(r'\sclass="[^"]*"', "", svg)
    svg = svg.replace('stroke="currentColor"', 'stroke="black"')
    svg = re.sub(r"\s+", " ", svg).strip().replace('"', "'")
    return "data:image/svg+xml," + urllib.parse.quote(svg, safe="/:=' ,.-")


def main() -> None:
    rules = [
        "/* AUTO-GENERATED by tools/build_icons.py — do not edit */",
        ".lucide{display:inline-block;flex-shrink:0;width:1rem;height:1rem;background-color:currentColor;"
        "-webkit-mask-repeat:no-repeat;mask-repeat:no-repeat;-webkit-mask-position:center;mask-position:center;"
        "-webkit-mask-size:contain;mask-size:contain;vertical-align:middle}",
    ]
    missing = []
    for name in sorted(used_names()):
        f = LUCIDE / f"{name}.svg"
        if not f.exists():
            missing.append(name)
            continue
        uri = to_data_uri(f.read_text(encoding="utf-8"))
        rules.append(f'.lucide-{name}{{-webkit-mask-image:url("{uri}");mask-image:url("{uri}")}}')
    OUT.write_text("\n".join(rules) + "\n", encoding="utf-8")
    print(f"wrote {OUT} ({len(rules) - 2} icons)")
    if missing:
        print("MISSING:", missing)


if __name__ == "__main__":
    main()
