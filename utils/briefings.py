"""
Standard briefings (country profile + transparency brief).

Port of `web/lib/briefings.ts` (registry), `rag/app/api/country_profile.py` /
`country_transparency.py` (context assembly), `rag/app/ingestion/repo_source.py` (scope helpers) and the
`/api/briefings` cache.  The original streamed tokens over SSE; the mAI gateway cannot stream, so a
briefing is generated by a **background job** that reports status lines (“Preparing…”, “Found N
records…”) while the page polls it (see utils/jobs.py) and returns the complete markdown at the end.
"""

from __future__ import annotations

import logging
import re
from collections import Counter

import constants as C
from utils import jobs, mai_client, prompts, queries, rag, translate

log = logging.getLogger(__name__)

BRIEFING_LIST = [
    {
        "key": "profile",
        "label": "Country Profile",
        "title": "Country PIM Institutional Profile",
        "description": ("A comprehensive institutional profile of a country's public investment management "
                        "framework — the institutional map, policy hierarchy, and the 8 must-have PIM stages — with "
                        "a listing of repository documents by tier."),
        "file_prefix": "PIM_Profile",
        "lang_toggle": True,
        "query": "Public investment management institutional framework for {name}",
        "generating": "profile",
        "page": "country-profile",
    },
    {
        "key": "transparency",
        "label": "Transparency Brief",
        "title": "Country PIM Transparency Assessment",
        "description": ("A Transparency International–style advocacy brief assessing the transparency and "
                        "disclosure mandates in a country's PIM framework, benchmarked against international good "
                        "practice (World Bank, IMF PIMA, EU)."),
        "file_prefix": "PIM_Transparency",
        "lang_toggle": True,
        "query": "Public investment management institutional framework policy transparency for {name}",
        "generating": "transparency briefing",
        "page": "country-transparency",
    },
]
SCOPE_RE = re.compile(r"^(all|national|sub:.{1,100})$")
MIN_CONTENT = C.BRIEFING_MIN_CONTENT
MAX_CONTENT = C.BRIEFING_MAX_CONTENT
PROFILE_MAX_TOKENS = C.PROFILE_MAX_TOKENS


def get_briefing(key: str) -> dict | None:
    return next((b for b in BRIEFING_LIST if b["key"] == key), None)


# ── record selection (rag/app/ingestion/repo_source.py) ──────────────────────
def filter_records_for_lang(records: list[dict], use_ori: bool) -> list[dict]:
    def keep(doc: dict) -> bool:
        lt = (doc.get("lang_type") or "").upper()
        if use_ori:
            return lt == "ORI"
        return lt == "ENG" or (lt == "ORI" and (doc.get("lang_code") or "").lower() == "en")

    out = []
    for r in records:
        docs = [d for d in r.get("documents", []) if keep(d)]
        if docs:
            out.append({**r, "documents": docs})
    return out


def filter_records_current(records: list[dict]) -> list[dict]:
    return [r for r in records if (r.get("record_status") or "latest").lower() != "archived"]


def filter_records_by_scope(records: list[dict], scope: str | None) -> list[dict]:
    if not scope or scope == "all":
        return records
    if scope == "national":
        return [r for r in records if (r.get("jurisdiction_level") or "national") != "subnational"]
    if scope.startswith("sub:"):
        entity = scope[4:].strip().lower()
        return [r for r in records if (r.get("jurisdiction_level") or "") == "subnational"
                and (r.get("jurisdiction_name") or "").strip().lower() == entity]
    return records


def select_briefing_records(records: list[dict], use_ori: bool, scope: str | None) -> tuple[list[dict], list[str]]:
    """→ (context_records, retrieval_ids).  `retrieval_ids` = every CURRENT in-scope record (any language);
    an empty list means nothing to analyse (never fall back to unfiltered country-wide retrieval)."""
    in_scope = filter_records_by_scope(filter_records_current(records), scope)
    ids = [str(r["id"]) for r in in_scope if r.get("id")]
    return filter_records_for_lang(in_scope, use_ori), ids


def scope_display_name(country_name: str, scope: str | None) -> str:
    if scope and scope.startswith("sub:"):
        return f"{scope[4:].strip()} ({country_name})"
    if scope == "national":
        return f"{country_name} (national framework)"
    return country_name


def dominant_ori_language(records: list[dict]) -> str | None:
    labels = [d["lang_label"] for r in records for d in r.get("documents", [])
              if (d.get("lang_type") or "").upper() == "ORI" and d.get("lang_label")]
    return Counter(labels).most_common(1)[0][0] if labels else None


# ── generation job ───────────────────────────────────────────────────────────
def _status(job_id: str, text: str, detail: str | None = None) -> None:
    jobs.update(job_id, status_text=text, detail=detail)


def generate(job_id: str, key: str, iso3: str, lang: str, scope: str, repo_url: str = "",
             model: str | None = None) -> dict:
    """`model` = one of mai_client.available_models() (None → the default model)."""
    spec = get_briefing(key)
    if not spec:
        raise ValueError("Unknown briefing.")
    use_ori = lang.upper() == "ORI"
    scope = (scope or "all").strip()
    iso3 = iso3.upper()
    if not mai_client.is_configured():
        raise mai_client.MaiError(mai_client.NOT_CONFIGURED)

    names = queries.country_name_map()
    country_name = names.get(iso3) or iso3
    profile_name = scope_display_name(country_name, scope)
    lang_label = "original-language" if use_ori else "English"
    _status(job_id, f"Preparing {lang_label} {spec['generating']} for {profile_name}...")

    records, rec_ids = select_briefing_records(queries.get_country_records_with_documents(iso3), use_ori, scope)
    if not rec_ids:
        raise ValueError(
            "No current (non-archived) repository records match the selected jurisdiction scope." if scope != "all"
            else "This country has no current (non-archived) repository records to analyse.")
    brief_key = spec["key"]
    policy_context = prompts.format_policy_records_context(records, with_uuid=prompts.BRIEFINGS[brief_key]["with_uuid"])
    _status(job_id, f"Found {len(records)} {lang_label} policy records. Retrieving document context...")

    filters: dict = {"country": iso3, "record_id": rec_ids}
    base_query = spec["query"].format(name=profile_name)
    search: str | list[str] = base_query
    ori_language = dominant_ori_language(records) if use_ori else None
    if use_ori:
        filters["lang_type"] = "ORI"
        translated = translate.translate_query(base_query, ori_language or "the original language of the documents")
        search = [translated, base_query] if translated else base_query
    retrieval_error = None
    try:
        docs = rag.retrieve(search, filters=filters, k=C.BRIEFING_RETRIEVER_K, pad_to_k=True)
    except Exception as exc:  # noqa: BLE001 - the original falls back to “no indexed documents”
        log.exception("briefing retrieval failed")
        docs, retrieval_error = [], type(exc).__name__
    if docs:
        rag_context = prompts.format_documents(docs)
        _status(job_id, f"Retrieved {len(docs)} document excerpts. Generating {spec['generating']}...")
    else:
        rag_context = "No indexed documents available."
        _status(job_id, "No indexed documents available. Generating from general knowledge...", retrieval_error)

    directive = prompts.ori_language_directive(ori_language) if use_ori else ""
    system, human = prompts.build_briefing_messages(brief_key, profile_name, policy_context, rag_context, directive,
                                                    prompts.repo_base_url(repo_url))
    content = mai_client.generate(system, human, max_tokens=PROFILE_MAX_TOKENS if brief_key == "profile"
                                  else C.BRIEFING_MAX_TOKENS, temperature=0.2, model=model)
    return {"content": content, "country_name": profile_name, "sources": len(docs)}


def start(key: str, iso3: str, lang: str, scope: str, repo_url: str = "", model: str | None = None) -> str:
    return jobs.submit("briefing", generate, key, iso3, lang, scope, repo_url, model)


# ── cache (GET/POST /api/briefings) ──────────────────────────────────────────
def valid_params(key: str, country: str, lang: str, scope: str) -> bool:
    return bool(get_briefing(key) and country and lang in ("ENG", "ORI") and SCOPE_RE.match(scope or ""))


def get_cached(key: str, country: str, lang: str, scope: str = "all") -> dict | None:
    if not valid_params(key, country.upper(), lang.upper(), scope):
        return None
    return queries.get_cached_briefing(key, country.upper(), lang.upper(), scope)


def save_cached(key: str, country: str, lang: str, scope: str, content: str):
    if not valid_params(key, country.upper(), lang.upper(), scope) or not (MIN_CONTENT <= len(content) <= MAX_CONTENT):
        raise ValueError("Invalid payload")
    return queries.upsert_cached_briefing(key, country.upper(), lang.upper(), content, scope)
